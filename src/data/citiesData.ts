export function getCityById(cityId: string): City {
  const found = INDIAN_CITIES.find(c => c.id.toLowerCase() === cityId.toLowerCase());
  return found || INDIAN_CITIES[0]; // defaults to Pune
}

export function getAreaById(city: City, areaId?: string) {
  if (!areaId) return city.areas[0];
  const found = city.areas.find(a => a.id.toLowerCase() === areaId.toLowerCase());
  return found || city.areas[0];
}
